#!/usr/bin/env python3
"""Embed sql/*.sql into src/kdb/SchemaSql.gen.cpp so the server bootstraps without loose files."""
import glob
import os
import sys

HEADER = '''// kdb/SchemaSql.gen.cpp - GENERATED by tools/gen_schema.py, do not edit.
// The migration scripts are compiled in so the server can bootstrap an empty database file
// without shipping loose .sql files (MSVC build and Linux build share the same list).
#include "kdb/Schema.h"

namespace knc::db {

const std::vector<std::pair<std::string, std::string>>& embeddedScripts() {
    static const std::vector<std::pair<std::string, std::string>> scripts = {
'''


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else '.'
    files = sorted(glob.glob(os.path.join(root, 'sql', '*.sql')))
    if not files:
        print('no sql scripts found', file=sys.stderr)
        return 1
    out = [HEADER]
    for path in files:
        name = os.path.basename(path)
        sql = open(path, encoding='utf-8').read()
        escaped = sql.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n"\n        "')
        out.append('        {"%s",\n        "%s"},\n' % (name, escaped))
    out.append('    };\n    return scripts;\n}\n\n}  // namespace knc::db\n')
    target = os.path.join(root, 'src', 'kdb', 'SchemaSql.gen.cpp')
    open(target, 'w', encoding='utf-8').write(''.join(out))
    print('embedded %d scripts -> %s' % (len(files), target))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
