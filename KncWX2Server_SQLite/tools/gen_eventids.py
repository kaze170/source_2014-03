#!/usr/bin/env python3
"""Generate kproto/EventId.gen.h from the original 2014 event id headers.

The X2 client and server agree on event ids purely by enumeration order, and every `#ifdef` guard
inside the original EventID_*.h files is commented out in this snapshot, so the sequence of _ENUM
tokens is exactly the sequence of ids on the wire. Regenerating from the pristine headers keeps the
rewrite byte compatible instead of hand copying 5,000+ constants.

Usage:  python3 tools/gen_eventids.py <KncWX2Server/Common> <output header>
"""
import os
import re
import sys

ENUM_RE = re.compile(r'_ENUM\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*(?:=\s*([^)]*))?\)')
INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.M)


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    # Drop preprocessor lines (the _ENUM macro definition itself would otherwise match ENUM_RE).
    text = re.sub(r'^[ \t]*#[^\n]*$', '', text, flags=re.M)
    return text


def collect(path, base, seen_includes=None):
    """Returns [(name, explicit_value_or_None)] honouring #include directives."""
    items = []
    text = open(path, encoding='cp949', errors='replace').read()
    text = strip_comments(text)
    # Remove the never-defined guard blocks that merely wrap the enum.
    for current in range(64):
        pos = 0
        out = []
        while True:
            m = INCLUDE_RE.search(text, pos)
            if not m:
                out.append(text[pos:])
                break
            out.append(text[pos:m.start()])
            inc = m.group(1).replace('\\', '/')
            inc_path = os.path.join(base, inc)
            if os.path.exists(inc_path):
                out.append('\n' + '\n'.join('%s %s' % (n, v if v else '') for n, v in collect(inc_path, base)))
            pos = m.end()
        new_text = ''.join(out)
        if new_text == text:
            break
        text = new_text
    for m in ENUM_RE.finditer(text):
        name = m.group(1)
        value = m.group(2)
        if value is not None:
            value = value.strip()
        items.append((name, value))
    return items


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    common, out_path = sys.argv[1], sys.argv[2]
    groups = [
        ('kSystem', 'EventID_System.h'),
        ('kClient', 'EventID_Client.h'),
        ('kServer', 'EventID_Server.h'),
    ]

    lines = []
    names = []
    index = 0
    for prefix, header in groups:
        items = collect(os.path.join(common, header), common)
        lines.append('// %s: %s (%d ids)' % (prefix, header, len(items)))
        prev_name = None
        for name, value in items:
            if value is not None:
                lines.append('inline constexpr EventId %s = %s;  // %d' % (name, value, index))
            elif prev_name is None:
                lines.append('inline constexpr EventId %s = %d;' % (name, index))
            else:
                lines.append('inline constexpr EventId %s = %s + 1;' % (name, prev_name))
            names.append(name)
            prev_name = name
            index += 1
        lines.append('')

    header = f'''// kproto/EventId.gen.h - GENERATED by tools/gen_eventids.py, do not edit.
//
// Event ids of the 2014 X2 protocol, in the exact enumeration order the client uses.
// Total: {index} ids (system + client + server).
#pragma once

#include "kcore/Types.h"

namespace knc {{

using EventId = std::uint16_t;

// System ids (EventID_System.h) start at 0.
// Client ids (EventID_Client.h) continue right after the system ids.
// Server ids (EventID_Server.h) continue right after the client ids.
''' + '\n'.join(lines) + f'''

inline constexpr std::size_t kEventIdCount = {index};

// Returns the symbolic name of an event id, or "E_UNKNOWN" when out of range.
const char* eventIdName(EventId id);

}}  // namespace knc
'''
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w') as f:
        f.write(header)

    # name table
    table = ['// kproto/EventIdName.gen.cpp - GENERATED by tools/gen_eventids.py, do not edit.',
             '#include "kproto/EventId.h"', '', 'namespace knc {', '',
             'namespace {', 'constexpr const char* kEventIdNames[kEventIdCount] = {']
    for n in names:
        table.append('    "%s",' % n)
    table.append('};')
    table.append('}  // namespace')
    table.append('')
    table.append('const char* eventIdName(EventId id) {')
    table.append('    if (id >= kEventIdCount) return "E_UNKNOWN";')
    table.append('    return kEventIdNames[id];')
    table.append('}')
    table.append('')
    table.append('}  // namespace knc')
    cpp_path = os.path.join('src', 'kproto', 'EventIdName.gen.cpp')
    os.makedirs(os.path.dirname(cpp_path), exist_ok=True)
    with open(cpp_path, 'w') as f:
        f.write('\n'.join(table) + '\n')
    print('generated %d event ids -> %s' % (index, out_path))
    return 0


if __name__ == '__main__':
    sys.exit(main())
