#!/usr/bin/env python3
"""Embeds the per class/level base stats from ServerResource/StatTable.lua.

StatTable.lua is the 2014 Lua resource that the original GameServer fed into KStatTable:
    StatTable:ReserveMemory( <class>, <max level> )
    StatTable:SetUnitStat( <class>, <level>, { AtkPhysic = .., AtkMagic = .., DefPhysic = ..,
                                              DefMagic = .., HP = .. } )
The rewrite compiles the same numbers into a flat lookup table so kgame can resolve a unit's base
KStat without a Lua interpreter or a resource directory.

Usage:  python3 tools/gen_stat_table.py [path/to/StatTable.lua]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_LUA = ROOT.parent / "KncWX2Server" / "ServerResource" / "StatTable.lua"
OUT_CPP = ROOT / "src" / "kgame" / "StatTableData.gen.cpp"

UNIT_STAT_RE = re.compile(r"StatTable\s*:\s*SetUnitStat\s*\(\s*(\d+)\s*,\s*(\d+)\s*,\s*\{([^}]*)\}\s*\)")
FIELD_RE = re.compile(r"(\w+)\s*=\s*([-\d.]+)")
RESERVE_RE = re.compile(r"StatTable\s*:\s*ReserveMemory\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)")

FIELDS = ["HP", "AtkPhysic", "AtkMagic", "DefPhysic", "DefMagic"]


def parse(lua_text: str) -> tuple[dict[int, int], dict[tuple[int, int], dict[str, float]]]:
    reserved: dict[int, int] = {int(c): int(n) for c, n in RESERVE_RE.findall(lua_text)}
    stats: dict[tuple[int, int], dict[str, float]] = {}
    for klass, level, body in UNIT_STAT_RE.findall(lua_text):
        values = {name: float(value) for name, value in FIELD_RE.findall(body)}
        unknown = set(values) - set(FIELDS)
        if unknown:
            raise ValueError(f"unknown stat field(s) {sorted(unknown)} for class {klass} level {level}")
        stats[(int(klass), int(level))] = values
    return reserved, stats


def main(argv: list[str]) -> int:
    lua_path = Path(argv[1]) if len(argv) > 1 else DEFAULT_LUA
    reserved, stats = parse(lua_path.read_text(encoding="utf-8-sig"))
    if not stats:
        raise ValueError("no SetUnitStat rows found")

    classes = sorted({klass for klass, _ in stats})
    max_level = max(level for _, level in stats)

    # Sorted by (class, level) so StatTable can binary search without an index array. Classes keep
    # their original class codes, gaps included (9, 32..99 have no rows in the source table).
    flat: list[tuple[int, int, float, float, float, float, float]] = []
    for klass in classes:
        for level in range(1, max_level + 1):
            values = stats.get((klass, level))
            if values is None:
                continue
            flat.append(
                (
                    klass,
                    level,
                    values.get("HP", 0.0),
                    values.get("AtkPhysic", 0.0),
                    values.get("AtkMagic", 0.0),
                    values.get("DefPhysic", 0.0),
                    values.get("DefMagic", 0.0),
                )
            )

    OUT_CPP.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// src/kgame/StatTableData.gen.cpp - generated by tools/gen_stat_table.py; do not edit.",
        "//",
        f"// Source: {lua_path.name} ({len(stats)} SetUnitStat rows, {len(classes)} classes, "
        f"levels 1..{max_level}).",
        '#include "kgame/StatTable.h"',
        "",
        "namespace knc::game {",
        "namespace {",
        "",
        f"constexpr StatEntry kStatTable[{len(flat)}] = {{",
    ]
    for klass, level, hp, atk_physic, atk_magic, def_physic, def_magic in flat:
        lines.append(
            f"    {{{klass}, {level}, "
            f"{_fmt(hp)}, {_fmt(atk_physic)}, {_fmt(atk_magic)}, {_fmt(def_physic)}, {_fmt(def_magic)}}},"
        )
    lines += [
        "};",
        "",
        "const int kClassCodes[] = {" + ", ".join(str(c) for c in classes) + "};",
        f"constexpr int kClassCodeCount = {len(classes)};",
        f"constexpr int kMaxLevel = {max_level};",
        "",
        "}  // namespace",
        "",
        "const StatEntry* statTableData() { return kStatTable; }",
        "std::size_t statTableSize() { return " + str(len(flat)) + "; }",
        "const int* statTableClasses() { return kClassCodes; }",
        "std::size_t statTableClassCount() { return static_cast<std::size_t>(kClassCodeCount); }",
        "int statTableMaxLevel() { return kMaxLevel; }",
        "",
        "}  // namespace knc::game",
        "",
    ]
    OUT_CPP.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"{OUT_CPP.relative_to(ROOT)}: {len(flat)} rows, {len(classes)} classes, max level {max_level}"
    )
    return 0


def _fmt(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else repr(value)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
