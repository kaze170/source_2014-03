#!/usr/bin/env python3
"""Generate kproto/FeatureFlags.gen.h from the original ServerDefine.h.

ServerDefine.h is a switchboard of ~523 `#define SERV_*` feature macros that select protocol
variants inside the shared packet headers (ClientPacket.h, CommonPacket.h, ServerPacket.h). The
2014 service build has a specific combination enabled; the rewrite must reproduce the same
combination or the packet layouts silently diverge.

Usage: python3 tools/gen_featureflags.py <KncWX2Server/Common/ServerDefine.h> <out header>
"""
import re
import sys

DEFINE_RE = re.compile(r'^\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)', re.M)
COMMENTED_RE = re.compile(r'^\s*//\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)', re.M)


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    src, out = sys.argv[1], sys.argv[2]
    text = open(src, encoding='cp949', errors='replace').read()

    enabled = []
    for m in DEFINE_RE.finditer(text):
        name = m.group(1)
        if name not in enabled:
            enabled.append(name)
    disabled = []
    for m in COMMENTED_RE.finditer(text):
        name = m.group(1)
        if name not in enabled and name not in disabled:
            disabled.append(name)

    lines = [
        '// kproto/FeatureFlags.gen.h - GENERATED by tools/gen_featureflags.py, do not edit.',
        '//',
        '// Feature macros that select packet variants in the shared 2014 headers. The rewrite mirrors',
        '// the service build configuration: kFeature* constants answer "is this variant active?".',
        '#pragma once',
        '',
        'namespace knc::features {',
        '',
        '// ---- enabled in the 2014 build (%d) ----' % len(enabled),
    ]
    for name in enabled:
        lines.append('inline constexpr bool k%s = true;' % name)
    lines.append('')
    lines.append('// ---- present but disabled in the 2014 build (%d) ----' % len(disabled))
    for name in disabled:
        lines.append('inline constexpr bool k%s = false;' % name)
    lines += ['', '}  // namespace knc::features', '']
    open(out, 'w').write('\n'.join(lines))
    print('feature flags: %d enabled, %d disabled -> %s' % (len(enabled), len(disabled), out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
